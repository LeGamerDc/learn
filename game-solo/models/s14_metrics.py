"""
14 章：指标、埋点与调优

三段：
  ① **指标树**：把收入公式一层层拆到可埋点的字段
  ② **广告漏斗**：触发 → 发起 → 加载 → 看完 → 发奖，每一步都会掉人
  ③ **AB 实验的样本量**：本章最实用的一段，也是最容易被低估的一段

第 ③ 段会得出一个对小团队很不友好、但必须面对的结论。
"""
import numpy as np
import matplotlib.pyplot as plt
from cnfont import use_cjk_font

use_cjk_font()

Z_A, Z_B = 1.96, 0.84          # 双侧 α=0.05，功效 80%

# ============================================================
# ① 指标树
# ============================================================
print("""=== ① 指标树：把收入公式拆到可埋点的字段 ===

    日收入 = DAU × IPU × eCPM ÷ 1000 × 分成
              │      │       │
    ┌─────────┘      │       └──── 平台侧，你只能通过"人群质量"间接影响
    │                │
    │         ┌──────┴────────────────────────────┐
    │         │  IPU = 会话数/人 × 每会话广告次数    │
    │         │           │              │         │
    │         │    离线上限(第11章)   点位设计(第05章) │
    │         └───────────────────────────────────┘
    │
    └── DAU = 新增 + 留存×昨日DAU
              │        │
          买量/自然量   ├── 次留 ← 前 3 分钟闭环（第 02 章）
                       ├── 7 留 ← 会话结构、元进程（第 11、12 章）
                       └── 30留 ← 内容寿命（第 03、12 章）

**读法：每一个叶子节点，都要对应至少一个埋点字段。**
如果某个叶子你埋不到，那条链路上的问题你永远看不见。
""")

FIELDS = [
    ("会话开始/结束", "会话数/人、单次会话时长", "第 11 章的离线上限调对了吗"),
    ("单局开始/结束/结果", "每会话局数、通关率、死亡房间", "第 02、06 章"),
    ("广告点位触发", "各点位的触发次数", "第 05 章的触达率"),
    ("广告发起/完成", "各点位的渗透率与完成率", "本章第 ② 段的漏斗"),
    ("三选一的选项与选择", "道具选取率、构筑分布", "第 07 章的 dominant 判据"),
    ("元进程等级变化", "内容消耗速度", "第 12 章的产能倒推"),
    ("离线收益领取", "离线上限的实际吃满率", "第 11 章"),
]
print(f"{'埋点事件':<22}{'能算出什么':<28}{'对应哪一章的判据'}")
print("-" * 84)
for a, b, c in FIELDS:
    print(f"{a:<20}{b:<26}{c}")

print("""
⚠️ **最容易漏的是"三选一的选项"** ——
   大多数人只埋"玩家选了什么"，不埋"当时给了他哪三个"。
   **没有分母，选取率就算不出来**，第 07 章那套判据全部失效。

   ⇒ **凡是"率"，都要同时埋分子和分母。** 这是埋点设计的第一条铁律。
""")

# ============================================================
# ② 广告漏斗
# ============================================================
print("=== ② 广告漏斗：每一步都会掉人 ===\n")

FUNNEL = [
    ("点位触发", 1.000, "玩家到达了这个点位（受生存曲线影响，第 05 章）"),
    ("展示按钮", 0.920, "冷却/每日上限/平台间隔限制挡掉一部分"),
    ("玩家点击", 0.480, "**这一步就是渗透率，第 05 章的意愿模型管的是它**"),
    ("广告加载成功", 0.940, "无填充、网络差 —— 纯工程问题，但直接吃收入"),
    ("完整看完", 0.910, "中途退出"),
    ("奖励发放", 0.995, "发奖失败 = 玩家投诉的主要来源"),
]

print(f"{'步骤':<16}{'单步转化':>10}{'累计':>10}{'每 1000 次触发剩':>16}   说明")
print("-" * 96)
cum = 1.0
for name, rate, note in FUNNEL:
    cum *= rate
    print(f"{name:<14}{rate:>10.1%}{cum:>10.1%}{cum*1000:>16.0f}   {note}")

print(f"""
读法
----
**1000 次触发，最后只有 {cum*1000:.0f} 次真正产生了广告收入。**

⇒ 两条实践含义：

  1. **算 IPU 时不能用"触发次数"，要用"完成次数"。**
     按触发次数算会**高估 {1/cum:.1f} 倍**。

  2. **"广告加载成功率"和"完整看完率"是工程指标，不是设计指标，
     但它们直接乘在收入上。**
     加载成功率从 94% 掉到 85%，收入直接掉 10% —— 而这通常是
     SDK 配置、预加载时机、网络重试的问题。**上线后先查这两个数。**

⚠️ 漏斗里唯一由数值设计决定的是"玩家点击"那一步（渗透率 {FUNNEL[2][1]:.0%}）。
   **其余五步都是产品/工程问题。**
   新手容易花大力气调奖励倍率去提渗透率，
   **却没发现真正的漏在加载失败上。** 先看漏斗，再调数值。
""")

# ============================================================
# ③ AB 实验的样本量
# ============================================================
print("=== ③ AB 实验：你的 DAU 撑得起什么样的实验 ===\n")


def n_continuous(sigma, delta):
    """连续指标（如 IPU）每组需要的样本量"""
    return 2 * (Z_A + Z_B) ** 2 * sigma ** 2 / delta ** 2


def n_binary(p, delta):
    """二元指标（如次留）每组需要的样本量"""
    return 2 * (Z_A + Z_B) ** 2 * p * (1 - p) / delta ** 2


DAU = 5000                  # 独立开发者的典型量级
NEW_PER_DAY = 800           # 每日新增（留存类实验只能用新增用户）

# (名称, 类型, 基线, 标准差, 效应, 每日可入组人数, 观察期天数, 备注)
CASES = [
    ("IPU +5%",     "连续", 6.0, 4.0, 0.30, DAU / 2, 0, "老+新用户都能进组"),
    ("IPU +10%",    "连续", 6.0, 4.0, 0.60, DAU / 2, 0, ""),
    ("次留 +5pp",   "二元", 0.40, None, 0.05, NEW_PER_DAY / 2, 1, "只能用新增用户"),
    ("次留 +2pp",   "二元", 0.40, None, 0.02, NEW_PER_DAY / 2, 1, ""),
    ("7留 +1.5pp",  "二元", 0.15, None, 0.015, NEW_PER_DAY / 2, 7, "还要等观察期"),
    ("30留 +1pp",   "二元", 0.06, None, 0.010, NEW_PER_DAY / 2, 30, ""),
    ("LTV(30) +5%", "连续", 0.86, 1.30, 0.043, NEW_PER_DAY / 2, 30, "方差大得多"),
]

print(f"（DAU {DAU:,}，日新增 {NEW_PER_DAY:,}，α=0.05，功效 80%，两组均分）\n")
print(f"{'想检测的效应':<16}{'类型':>6}{'每组需要样本':>14}{'入组天数':>10}"
      f"{'+观察期':>9}{'总天数':>9}   备注")
print("-" * 92)
rows = []
for name, kind, base, sd, delta, per_day, wait, note in CASES:
    n = n_continuous(sd, delta) if kind == "连续" else n_binary(base, delta)
    days = n / per_day + wait
    rows.append((name, n, days))
    flag = "" if days <= 14 else ("  ⚠️ 偏长" if days <= 45 else "  ❌ 做不了")
    print(f"{name:<14}{kind:>6}{n:>14,.0f}{n/per_day:>10.1f}{wait:>9}"
          f"{days:>9.1f}{flag}   {note}")

print(f"""
读法 —— **本章最该记住的一段**
------------------------------
**留存类实验比 IPU 类实验难一到两个数量级。** 原因有三条，且是叠加的：

  1. **二元指标的方差大。** 次留是 0/1，没有中间值。
  2. **只能用新增用户。** 老用户的留存已经被历史影响了，
     所以分母从 DAU 掉到"日新增"，本模型里少了 {DAU/NEW_PER_DAY:.1f} 倍。
  3. **还要等观察期。** 测 7 留要多等 7 天，测 30 留要多等 30 天。

⚠️ **而第 04 章证明过：留存是超线性杠杆，IPU 是线性杠杆。**

    ⇒ **你最想优化的那个东西，恰恰是最难用 AB 验证的。**
      这不是你的产品的问题，是统计学的性质。

⇒ **给小团队的三条应对（按优先级）：**

  1. **能用大效应就别测小效应。**
     "次留 +2pp"要 {rows[3][2]:.0f} 天，"次留 +5pp"只要 {rows[2][2]:.0f} 天 —— **差 {rows[3][2]/rows[2][2]:.0f} 倍。**
     **与其做十个 +1% 的微调，不如做一个 +5% 的大改。**
     小团队的 AB 只适合验证"方向对不对"，不适合"抠效率"。

  2. **小效应用模型和判断，不用 AB。**
     第 06 章那个 LTV 曲面就是为此存在的 ——
     **模型不需要样本量。** 它的代价是假设可能错，
     但"假设可能错"总好过"根本测不出来"。

  3. **用代理指标缩短周期。**
     测"次留"要等 1 天，但**"首次会话时长"和"首次会话内是否完成一局"**
     当天就能看到，而且和次留高度相关。
     ⇒ **先用代理指标快速筛掉明显更差的版本，再用真指标验证少数几个。**

⚠️ 最后一个坑：**别做多个并行 AB 然后挑最好看的那个。**
   跑 10 个实验，即使全是无效改动，也有 {1-0.95**10:.0%} 的概率至少有一个
   "显著"（α=0.05）。**这就是 p-hacking，在小样本下尤其致命。**
   要么预先声明主指标，要么做多重比较校正。
""")

# ============================================================
# ④ 上线后按什么顺序调
# ============================================================
print("""=== ④ 上线后按什么顺序调 ===

**顺序不是随意的，它由"改动成本"和"确定性"共同决定：**

  第 1 步  查漏斗的工程步骤（加载成功率、完成率）
          ├─ 成本：几乎为零（改配置）
          └─ 确定性：极高（这是 bug，不是权衡）

  第 2 步  查前 3 分钟的闭环完成率（第 02 章）
          ├─ 成本：低（调新手难度、缩短引导）
          └─ 确定性：高（次留是超线性杠杆）

  第 3 步  查通关率分布是否在健康带内（第 06、07 章）
          ├─ 成本：低（改配表）
          └─ 确定性：中（要看你的钟形曲线假设准不准）

  第 4 步  查内容消耗速度 vs 产能（第 12 章）
          ├─ 成本：高（要么做内容，要么降增速——后者玩家会骂）
          └─ 确定性：高（这是算术）

  第 5 步  调广告倍率和点位（第 05、06 章）
          ├─ 成本：低，但**投放能加不能减**（第 01 章）
          └─ 确定性：中

⚠️ **第 5 步排在最后是有意的。** 它见效最快，所以最诱人 ——
   但它也是**最难回退**的一步：广告奖励调低会被骂惨。
   **先把前四步的免费收益吃干净，再动变现旋钮。**
""")

# ============================================================
# 出图
# ============================================================
fig, axes = plt.subplots(1, 3, figsize=(16, 4.8))

names = [f[0] for f in FUNNEL]
cums, c = [], 1.0
for _, r, _ in FUNNEL:
    c *= r
    cums.append(c * 100)
axes[0].barh(range(len(names))[::-1], cums, color="tab:blue")
axes[0].set_yticks(range(len(names))[::-1]); axes[0].set_yticklabels(names, fontsize=8)
axes[0].set_xlabel("累计留存 %")
axes[0].set_title(f"① 广告漏斗\n1000 次触发只剩 {cums[-1]*10:.0f} 次收入")

lbl = [r[0] for r in rows]
dys = [r[2] for r in rows]
cols = ["tab:green" if d <= 14 else ("tab:orange" if d <= 45 else "tab:red")
        for d in dys]
axes[1].barh(lbl, dys, color=cols)
axes[1].axvline(14, color="k", ls=":", lw=1.5)
axes[1].text(15, -0.4, "两周", fontsize=8)
axes[1].set_xscale("log"); axes[1].set_xlabel("需要的实验天数（对数轴）")
axes[1].set_title("② AB 实验的可行性\n留存类实验难一到两个数量级")

deltas = np.linspace(0.005, 0.08, 60)
axes[2].plot(deltas * 100, [n_binary(0.40, d) / (NEW_PER_DAY / 2) for d in deltas],
             lw=2.5, color="tab:red", label="次留（二元，只能用新增）")
axes[2].plot(deltas * 100, [n_continuous(4.0, d * 15) / (DAU / 2) for d in deltas],
             lw=2.5, color="tab:blue", label="IPU（连续，全量用户）")
axes[2].axhline(14, color="k", ls=":", lw=1.5)
axes[2].set_yscale("log")
axes[2].set_xlabel("想检测的效应大小 %"); axes[2].set_ylabel("需要的天数（对数轴）")
axes[2].set_title("③ 效应越小，代价指数上升\n所以要做大改动，不做微调")
axes[2].legend(fontsize=8)

for ax in (axes[0], axes[1], axes[2]):
    ax.grid(alpha=.3, axis="x")
plt.tight_layout()
plt.savefig("../figures/s14_metrics.png", dpi=140)
