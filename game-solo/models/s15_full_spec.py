"""
15 章：端到端实战 —— 从 6 个决策生成完整数值方案

输入是**制作人层面的 6 个决策**（不是数值参数）：

    1. 品类           割草 / 放置
    2. 单局时长       秒
    3. 目标次留       %
    4. 内容产能       你一个月能做出多少"级"的内容
    5. 增长方式       买量 / 自然量
    6. 难度取向       偏易 / 标准 / 偏难

输出是一份可以直接开工的数值方案，并**自动检查它是否自洽**。

本模型是全课的收束：每一个推导都标了来源章节。
"""
import numpy as np

# ---------------- 全课沿用的常量 ----------------
ECPM, SHARE = 60.0, 0.50        # 第 04 章【行业口径 / 实证】
DECAY = 0.504                   # 第 04 章：留存幂律衰减
SESSION_MIN = 15.0              # 第 02、05 章
GRANT_RATE, GRANT_WINDOW = 0.40, 30    # 第 04 章【实证】2026 注册激励
BAND = (0.20, 0.45)             # 第 06、07 章的健康带


def spec(name, genre, run_sec, r1, content_per_month, growth, difficulty,
         prestige=True):
    S = {}
    S["名称"] = name

    # ---------- 第 02 章：会话结构 ----------
    runs_per_session = SESSION_MIN * 60 / (run_sec + 6)
    S["单局时长"] = f"{run_sec:.0f} 秒"
    S["每会话局数"] = runs_per_session
    S["会话装得下 3 局"] = runs_per_session >= 3

    # ---------- 第 06 章：难度 ----------
    winrate = {"偏易": 0.42, "标准": 0.31, "偏难": 0.22}[difficulty]
    S["目标通关率"] = winrate
    S["难度在健康带"] = BAND[0] <= winrate <= BAND[1]
    deaths_per_session = runs_per_session * (1 - winrate)
    S["每会话死亡次数"] = deaths_per_session

    # ---------- 第 11 章：会话数/天 ----------
    # 放置类靠离线上限拉会话数；割草类主要靠玩家自发回访
    sessions_per_day = 2.6 if genre == "放置" else 1.8
    S["离线上限建议"] = "8 小时（≈ 睡眠时长，第 11 章）" if genre == "放置" else "不适用"
    S["每天会话数"] = sessions_per_day

    # ---------- 第 05 章：广告点位与 IPU ----------
    if genre == "割草":
        places = [("复活", "局内", deaths_per_session, 3.0),
                  ("重抽三选一", "局内", 8.0, 1.2),
                  ("局内翻倍拾取", "局内", 5.0, 1.0),
                  ("结算翻倍", "局外", runs_per_session, 2.0),
                  ("每日免费领", "局外", 2.0, 2.5)]
    else:
        places = [("离线翻倍", "局外", 1.0, 6.0),
                  ("产出加速", "局外", 3.0, 2.2),
                  ("免费抽建筑", "局内", 4.0, 1.5),
                  ("双倍收菜", "局外", 3.0, 1.8),
                  ("每日免费领", "局外", 2.0, 2.5)]
    S["点位"] = places

    MULT = 2.5                                   # 第 05、06 章的起步倍率
    K, T, FAT = 1.2, 2.0, 0.40                  # 第 05 章的意愿模型
    # ⚠️ 疲劳必须**逐次触发**累积，不能按点位整体打折（第一版这么错过）。
    #    FAT=0.725 是每看一次真实广告后的衰减，和第 05 章同一套数字。
    seq = []
    for nm, layer, trig, base in places:
        seq += [(nm, layer, base)] * int(round(trig))
    rr = np.random.default_rng(7)
    rr.shuffle(seq)                              # 点位在会话内交错出现（第 05 章）
    ipu_session, k, by_place = 0.0, 0.0, {}
    for nm, layer, base in seq:
        p = 1 / (1 + np.exp(-K * (base * (MULT - 1) - T))) * FAT ** k
        ipu_session += p
        k += p
        by_place[nm] = by_place.get(nm, 0.0) + p
    S["各点位观看"] = by_place
    S["广告倍率"] = MULT
    S["每会话广告次数"] = ipu_session
    S["IPU"] = ipu = ipu_session * sessions_per_day

    # ---------- 第 03 章：广告注入 → 内容寿命 ----------
    inject = sum(by_place[n] * (MULT - 1) * b for n, layer, _, b in places
                 if layer == "局外") * sessions_per_day / (SESSION_MIN * 3)
    S["局外注入倍数"] = inject
    # 第 11 章：prestige 用同一批内容造出新的进度曲线，等效内容量约 ×2.5
    LEVELS = 100 * (2.5 if prestige else 1.0)
    S["prestige"] = prestige
    A = 5.0 * 100.0 * (1 + inject) / 300.0
    r = 1.030 / 1.035
    life = (1 - r ** (-LEVELS)) / (A * np.log(r))
    S["内容寿命"] = life

    # ---------- 第 12 章：产能校验 ----------
    need_per_month = LEVELS / (life / 30)
    S["需要月产能"] = need_per_month
    S["产能够用"] = content_per_month >= need_per_month

    # ---------- 第 04 章：收入与回本 ----------
    d = np.arange(91)
    ret = np.where(d == 0, 1.0, r1 * np.maximum(d, 1) ** (-DECAY))
    ret *= np.where(d <= life, 1.0, np.exp(-(d - life) / 7.0))
    S["次留"] = r1
    S["90天活跃天数"] = ret.sum()
    S["到手ARPDAU"] = arpdau = ipu * ECPM / 1000 * SHARE
    S["LTV90"] = ltv90 = ret.sum() * arpdau
    S["LTV30"] = ltv30 = ret[:31].sum() * arpdau
    S["广告金"] = grant = ret[:GRANT_WINDOW + 1].sum() * ipu * ECPM / 1000 * GRANT_RATE
    S["买量线"] = ltv30 + grant
    S["增长方式"] = growth
    S["CPA上限"] = (ltv30 + grant) if growth == "买量" else 0.0

    # ---------- 第 07、08、09 章：玩法参数 ----------
    S["池子结构"] = "通用模块 65% + 协同触发件 25% + 传说件 10%（第 07 章）"
    S["同维叠加"] = "软上限 1 + M·k/(k+K)，K ≈ 玩家典型堆叠件数（第 08、10 章）"
    S["协同门槛"] = "触发率目标 5%~15%（第 07 章）"
    S["保底"] = "硬保底，连续 2 次不出必出（第 09 章）"
    S["重抽上限"] = "每局 2~3 次（第 09 章：保住随机性，不是为了多看广告）"
    S["元进程"] = ("上线前用均匀型，有数据后换地板型；"
                   "地板对应的通关率必须在健康带内（第 12 章）")
    return S


def show(S):
    print(f"\n{'═' * 78}\n  {S['名称']}\n{'═' * 78}")

    def line(k, v, ok=None, src=""):
        mark = "" if ok is None else ("   ✅" if ok else "   ❌")
        print(f"  {k:<20}{v:<34}{src}{mark}")

    print("\n【单局与会话】")
    line("单局时长", S["单局时长"], src="第 02 章")
    line("每会话局数", f"{S['每会话局数']:.1f} 局",
         S["会话装得下 3 局"], "第 02 章（需 ≥3）")
    line("每天会话数", f"{S['每天会话数']:.1f} 次", src="第 11 章")
    line("离线上限", S["离线上限建议"], src="第 11 章")

    print("\n【难度】")
    line("目标通关率", f"{S['目标通关率']:.0%}", S["难度在健康带"],
         f"第 06 章（带 {BAND[0]:.0%}~{BAND[1]:.0%}）")
    line("每会话死亡", f"{S['每会话死亡次数']:.1f} 次", src="第 02 章 = 复活广告机会")

    print("\n【广告点位】（倍率 %.1f×，第 05、06 章）" % S["广告倍率"])
    print(f"  {'点位':<16}{'层':<8}{'每会话触发':<12}{'价值(分钟)':<12}{'实际观看'}")
    for n, layer, trig, base in S["点位"]:
        print(f"  {n:<16}{layer:<8}{trig:<12.1f}{base:<12.1f}"
              f"{S['各点位观看'][n]:.2f}")
    line("每会话广告次数", f"{S['每会话广告次数']:.2f}", src="第 05 章意愿模型")
    line("IPU", f"{S['IPU']:.2f}", 4.0 <= S["IPU"] <= 9.0, "第 04 章（目标 4~9）")

    print("\n【经济与内容】")
    line("局外注入倍数", f"{S['局外注入倍数']:.2f}×", src="第 03 章")
    line("内容寿命", f"{S['内容寿命']:.0f} 天", S["内容寿命"] >= 35, "第 03 章（需 ≥35）")
    line("prestige", "有（等效内容 ×2.5）" if S["prestige"] else "无",
         src="第 11 章")
    line("需要月产能", f"{S['需要月产能']:.0f} 级/月", S["产能够用"], "第 12 章")

    print("\n【收入与回本】")
    line("次留", f"{S['次留']:.0%}", src="第 04 章")
    line("90 天活跃天数", f"{S['90天活跃天数']:.1f} 天", src="第 04 章")
    line("到手 ARPDAU", f"{S['到手ARPDAU']:.3f} 元", src="第 04 章")
    line("LTV(30) 现金", f"{S['LTV30']:.2f} 元", src="第 04 章")
    line("LTV(90) 现金", f"{S['LTV90']:.2f} 元", src="第 04 章")
    line("广告金", f"{S['广告金']:.2f} 元", src="第 04 章【实证】首30天40%")
    line("买量线", f"{S['买量线']:.2f} 元", src="现金 + 广告金")
    if S["增长方式"] == "买量":
        line("CPA 上限", f"{S['CPA上限']:.2f} 元", src="超过就是亏本买量")
    else:
        line("增长方式", "自然量 / 社交裂变", src="第 04、12 章：分享是巅峰体验的副产品")

    print("\n【玩法参数】")
    for k in ("池子结构", "同维叠加", "协同门槛", "保底", "重抽上限", "元进程"):
        print(f"  {k:<20}{S[k]}")

    bad = [k for k, ok in (("会话装得下 3 局", S["会话装得下 3 局"]),
                           ("难度在健康带", S["难度在健康带"]),
                           ("IPU 达标", 4.0 <= S["IPU"] <= 9.0),
                           ("内容寿命达标", S["内容寿命"] >= 35),
                           ("产能够用", S["产能够用"])) if not ok]
    print(f"\n  {'─' * 74}")
    print(f"  自洽性检查：{'✅ 全部通过' if not bad else '❌ ' + '、'.join(bad)}")


# ============================================================
print("""
从 6 个制作人决策，生成完整数值方案
====================================
决策不是数值参数，而是产品判断。下面跑三套不同的决策，
看它们各自导出什么样的数值 —— **以及哪一套自己就不自洽。**
""")

A = spec("方案 A｜割草肉鸽 · 标准难度 · 自然量",
         genre="割草", run_sec=150, r1=0.40,
         content_per_month=40, growth="自然量", difficulty="标准")
show(A)

B = spec("方案 B｜放置经营 · 偏易 · 买量",
         genre="放置", run_sec=90, r1=0.45,
         content_per_month=40, growth="买量", difficulty="偏易")
show(B)

C = spec("方案 C｜割草肉鸽 · 偏难 · 买量（一个会失败的方案）",
         genre="割草", run_sec=300, r1=0.30,
         content_per_month=15, growth="买量", difficulty="偏难",
         prestige=False)
show(C)

print(f"""
{'═' * 78}
  三套方案的对比与读法
{'═' * 78}

**A（割草 · 自然量）**
   走的是"靠巅峰体验换分享"的路（第 04 章的第 1 条生路）。
   它不需要 CPA 回本，所以 LTV 低一点也活得下去。
   **代价：产品本身必须有强分享动机**（第 12 章 §6）。

**B（放置 · 买量）**
   放置类的 IPU 天然更高（第 10 章：加速点位价值都远超阈值），
   会话数也更高（离线上限拉回访）。**所以它才撑得起买量。**
   ⇒ **这不是巧合：微信小游戏的买量大盘以放置/经营类为主，就是这个原因。**

**C（一个会失败的方案，故意的）**
   单局 300 秒 → 一次会话装不下 3 局（第 02 章的硬约束）；
   偏难 → 通关率掉出健康带；
   月产能 15 级 → 撑不住内容消耗。
   **三条约束同时违反，而且它们互相加剧。**

   ⚠️ **注意 C 的每一个决策单独看都不离谱**："我想做个有深度的硬核肉鸽，
      一局 5 分钟，一个人慢慢做内容，靠买量起量。"
      **每句话都合理，合起来不自洽。**

⇒ **这就是本课全部 15 章的意义：**
   **让"合起来不自洽"在开工前就被发现，而不是上线三个月后。**

{'═' * 78}
  接下来做什么
{'═' * 78}

  1. 把你自己的 6 个决策填进 spec()，跑一遍，看自洽性检查
  2. 不通过的话，**改决策，不要改常量** ——
     常量（eCPM、分成、健康带、意愿阈值）是外部约束，不归你调
  3. 通过之后，把输出的参数表当成开工文档
  4. 做出原型 → 跑第 13 章的体检套件 → 上线 → 按第 14 章的顺序调

  ⚠️ 最后一句：**这份方案会错。**
     第 06 章那条钟形曲线是推导的，第 05 章的意愿模型是标定的，
     eCPM 明天就可能变。
     **方案的价值不在于"算得准"，在于它让每个假设都变成了显式的、
       可以被数据推翻的东西。**
""")
